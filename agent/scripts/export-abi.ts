// Copies the ABIs of the vault and the mocks from contracts/out/ to shared/deployments/abi/ for the frontend, and
// generates agent/src/chain/vault-abi.ts so the agent's types follow Person A's Vault exactly.
// Run `forge build` in contracts/ first, then `npm run export-abi`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const CONTRACTS = ['Vault', 'MockDEX', 'MockUSDC', 'MockAssetToken'] as const;

export const readAbi = (name: string): unknown[] =>
  (JSON.parse(readFileSync(new URL(`../../contracts/out/${name}.sol/${name}.json`, import.meta.url), 'utf8')) as { abi: unknown[] })
    .abi;

export const renderAbiModule = (vault: unknown[], mockUsdc: unknown[]) =>
  [
    '// Generated by agent/scripts/export-abi.ts from contracts/out/. Do not edit: run `forge build` in contracts/ and',
    '// `npm run export-abi` after the vault changes.',
    `export const vaultAbi = ${JSON.stringify(vault, null, 2)} as const;`,
    '',
    `export const mockUsdcAbi = ${JSON.stringify(mockUsdc, null, 2)} as const;`,
    '',
  ].join('\n');

if (import.meta.main) {
  const directory = new URL('../../shared/deployments/abi/', import.meta.url);
  mkdirSync(directory, { recursive: true });
  for (const name of CONTRACTS) {
    writeFileSync(new URL(`${name}.json`, directory), `${JSON.stringify(readAbi(name), null, 2)}\n`);
  }
  writeFileSync(
    new URL('../src/chain/vault-abi.ts', import.meta.url),
    renderAbiModule(readAbi('Vault'), readAbi('MockUSDC'))
  );
  console.log(`Wrote ${CONTRACTS.join(', ')} ABIs to shared/deployments/abi/ and agent/src/chain/vault-abi.ts`);
}
