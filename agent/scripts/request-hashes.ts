// Writes every request hash the vault stores, so Person A's deploy script and the agent use the same values.
// Run with `npm run request-hashes`.
import { readFileSync, writeFileSync } from 'node:fs';
import { deriveRequestHash } from '../src/airnode/attestation.ts';
import { loadProfiles, priceAirnode, priceRequest, type Profiles } from '../src/profiles.ts';
import { latestTweetRequest, type WatchedAccount } from '../src/sources/twitter.ts';

export const buildRequestHashes = (profiles: Profiles, watchlist: WatchedAccount[]) => ({
  $comment: 'Generated by agent/scripts/request-hashes.ts from shared/asset-profiles.json and agent/config/watchlist.json',
  prices: Object.fromEntries(
    Object.values(profiles.assets).map((asset) => [
      asset.key,
      {
        airnode: priceAirnode(profiles, asset).address,
        requestHash: deriveRequestHash(priceRequest(asset)),
        request: priceRequest(asset),
      },
    ])
  ),
  posts: Object.fromEntries(
    watchlist.map((account) => [
      account.handle,
      {
        airnode: profiles.airnodes.twitterapi?.address,
        pinned: account.pinned,
        requestHash: deriveRequestHash(latestTweetRequest(account)),
        request: latestTweetRequest(account),
      },
    ])
  ),
});

if (import.meta.main) {
  const watchlist = JSON.parse(
    readFileSync(new URL('../config/watchlist.json', import.meta.url), 'utf8')
  ) as WatchedAccount[];
  const hashes = buildRequestHashes(loadProfiles(), watchlist);
  writeFileSync(new URL('../../shared/deployments/request-hashes.json', import.meta.url), `${JSON.stringify(hashes, null, 2)}\n`);
  for (const [asset, { requestHash }] of Object.entries(hashes.prices)) console.log(`price ${asset.padEnd(5)} ${requestHash}`);
  for (const [handle, { requestHash }] of Object.entries(hashes.posts)) console.log(`post  @${handle.padEnd(16)} ${requestHash}`);
  console.log('Wrote shared/deployments/request-hashes.json');
}
